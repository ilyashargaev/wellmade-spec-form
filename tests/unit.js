const path=require('path'), vm=require('vm'), fs=require('fs');
const root=process.argv[2];
const ctx={console}; vm.createContext(ctx);
vm.runInContext('var window=globalThis;'+fs.readFileSync(path.join(root,'spec/presidio-xo.js'),'utf8'),ctx);
vm.runInContext(fs.readFileSync(path.join(root,'engine/model.js'),'utf8'),ctx);
const M=ctx.SpecEngine.createModel(ctx.SPEC_DATA);
let fails=0; const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m); if(!c) fails++;};
const J=x=>JSON.stringify(x);
let a=M.defaultAnswers();
ok(J(a.interior)===J(["back-left","back-right","right-lower"]),'interior base preselected');
ok(J(M.dynamicTags(M.question('interior'),a))===J({"back-left":"Included","back-right":"Included","right-lower":"Included"}),'base tags');
a=M.toggle(a,'interior','left-upper');
ok(M.dynamicTags(M.question('interior'),a)['left-upper']==='Additional charge','4th interior = Additional charge');
a=M.toggle(a,'interior','back-left');
ok(M.dynamicTags(M.question('interior'),a)['left-upper']==='Confirm in Comments','swap = Confirm in Comments');
a=M.toggle(a,'permits','building'); a=M.toggle(a,'permits','electrical');
ok(J(a.permits)===J(['building','electrical']),'building+electrical');
a=M.toggle(a,'permits','none'); ok(J(a.permits)===J(['none']),'NO permit clears others');
a=M.toggle(a,'permits','building'); ok(J(a.permits)===J(['building']),'building clears NO');
a=M.toggle(a,'connection','plug-in'); a=M.toggle(a,'connection','ethernet'); a=M.toggle(a,'connection','hardline');
ok(J(a.connection)===J(['ethernet','hardline']),'plug-in vs hardline exclusive, ethernet kept');
a=M.toggle(a,'exterior','back-left');
ok(M.dynamicTags(M.question('exterior'),a)['back-left']==='Pending breaker','pending before breaker');
a=M.toggle(a,'breaker','right-lower');
let t=M.dynamicTags(M.question('exterior'),a);
ok(t['right-lower']==='Included' && t['back-left']==='Extra charge','included follows breaker');
ok(M.optionState('exterior','right-lower',a).locked,'included locked');
let b=M.toggle(a,'exterior','right-lower'); ok(J(b.exterior)===J(a.exterior),'locked toggle no-op');
a=M.toggle(a,'breaker','back-right'); ok(a.breaker==='back-right','one breaker only (replace)');
t=M.dynamicTags(M.question('exterior'),a); ok(t['back-right']==='Included' && !t['right-lower'],'included moved with breaker');
a=M.toggle(a,'breaker','back-right'); ok(a.breaker===null,'tap again clears breaker');
a=M.toggle(a,'skylightLoc','left'); a=M.toggle(a,'skylightType','none');
ok(a.skylightLoc===null && M.isInactive('skylightLoc',a),'NO skylight clears + disables location');
b=M.toggle(a,'skylightLoc','left'); ok(b.skylightLoc===null,'disabled location cannot be set');
ok(M.controllerOf('skylightLoc',a)==='skylightType','controller');
ok(M.isInactive('dimA',a),'dims inactive when no deck');
a=M.toggle(a,'deckConfig','custom'); a=M.setText(a,'dimA','12'); ok(a.dimA==='12','dimA set when custom');
a=M.toggle(a,'deckConfig','standard'); ok(a.dimA==='' && M.isInactive('dimA',a),'non-custom deck clears A/B');
let s=M.summary(M.defaultAnswers());
ok(!s.open.some(o=>/Comments|Additions|customizations/.test(o.label)),'comments not open; open='+s.open.length);
let san=M.sanitize({decking:'gone',permits:['none','building','zzz'],interior:[],breaker:'Choice3',skylightType:'none',skylightLoc:'left',dimA:'5'});
ok(san.decking===null && J(san.permits)===J(['building']) && J(san.interior)===J([]) && san.breaker===null && san.skylightLoc===null && san.dimA==='','sanitize');
ok(J(M.sanitize('junk'))===J(M.defaultAnswers()),'sanitize junk');
let ex=M.exportAnswers(M.toggle(M.defaultAnswers(),'breaker','back-left'));
ok(J(ex.answers.exterior)===J(['back-left']),'export writes included exterior');
let ps=M.previewState(M.toggle(M.toggle(M.defaultAnswers(),'stain','stone-gray'),'decking','trex-select-saddle'));
ok(J(ps.layers.map(l=>[l.id,l.option,l.color]))===J([['facade','stone-gray','#9c9e9f'],['deck','trex-select-saddle','#85593c']]),'preview colors from spec');
ps=M.previewState(M.toggle(M.toggle(M.defaultAnswers(),'stain','natural-pine'),'decking','custom'));
ok(ps.picked && ps.layers.every(l=>l.color===null),'Natural Pine and custom decking keep the photo (color null)');
ok(!M.previewState(M.defaultAnswers()).picked,'nothing picked = empty preview');
ok(J(M.tagInfo(M.question('exterior'),M.toggle(M.toggle(M.defaultAnswers(),'breaker','back-left'),'exterior','right-upper')))===J({'back-left':{text:'Included',kind:'included'},'right-upper':{text:'Extra charge',kind:'extra'}}),'tag kinds for plan marks');
ok(J(M.tagLegend('exterior').map(t=>t.kind))===J(['included','extra','pending']) && M.tagLegend('breaker').length===0,'tag legend from rules');
ok(M.optionState('interior','back-left',M.defaultAnswers()).kind==='included','base interior outlet kind = included');
// ---- client link (Phase 3) ----
const E=ctx.SpecEngine, S=ctx.SPEC_DATA, LID='Ab3_k9-QpLm2Ts7v';
ok(J(E.linkFields(S).map(f=>[f.param,f.question,!!f.required]))===J([['name','client',true],['address','address',true],['phone','phone',false]]),'link fields declared in the spec');
let hash=E.linkHash(S,LID,{name:"Jane O'Brien & Co",address:'12 Main St #4, San Leandro, CA',phone:''});
ok(hash==="#id="+LID+"&name=Jane%20O%27Brien%20%26%20Co&address=12%20Main%20St%20%234%2C%20San%20Leandro%2C%20CA",'link hash encodes &, #, comma, quote, spaces; empty phone left out: '+hash);
let rl=E.readLink(S,hash);
ok(rl.id===LID && J(rl.values)===J({client:"Jane O'Brien & Co",address:'12 Main St #4, San Leandro, CA'}),'read back: values keyed by question id');
ok(E.readLink(S,'')===null && E.readLink(S,'#')===null,'no fragment = no link');
ok(!!E.readLink(S,'#id=short').error && !!E.readLink(S,'#name=Jane').error && !!E.readLink(S,'#id=bad%20id%20here!').error,'missing or bad id = error, not a link');
const usp='#'+new URLSearchParams({id:LID,name:'Ana María Núñez',address:'1 A+B Rd',phone:'+1 (510) 555-0100',extra:'x'}).toString();
rl=E.readLink(S,usp);
ok(J(rl.values)===J({client:'Ana María Núñez',address:'1 A+B Rd',phone:'+1 (510) 555-0100'}),'URLSearchParams-style fragment (+ for space) read, unicode kept, unknown param ignored');
rl=E.readLink(S,'#id='+LID+'&name=%E0%A4%A&address='+encodeURIComponent('Line1\nLine2\t')+'&phone='+'9'.repeat(400));
ok(!('client' in rl.values) && rl.values.address==='Line1 Line2' && rl.values.phone.length===300,'broken % skipped, control chars removed, values capped at 300');
ok(E.readLink(S,'#id='+LID+'&id=OtherIdOther1234').id===LID,'first id wins');
let la=M.applyLink(M.defaultAnswers(),{client:'Jane',address:'12 Main',interior:'x',nope:'y'});
ok(la.client==='Jane' && la.address==='12 Main' && J(la.interior)===J(["back-left","back-right","right-lower"]),'applyLink fills text questions only');
console.log(fails?fails+' FAILED':'ALL PASS'); process.exit(fails?1:0);
